export const dictionaries: Record<Locale, Dictionary> = { en, es, "pt-BR": pt };
export function dictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}
export function label(locale: Locale, code: string): string {
  const d = dictionary(locale);
  return Object.hasOwn(d, code) ? d[code as keyof Dictionary] : code;
}
export function money(value: string, locale: Locale): string {
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency: "BRL",
  }).format(Number(value));
}
export function month(value: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale, {
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${value}-01T12:00:00Z`));
}
export function date(value: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeZone: "UTC",
  }).format(new Date(value));
}
